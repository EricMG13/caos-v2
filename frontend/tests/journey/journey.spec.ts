// LITE run, driven through the real edge and the real API -- no fixture, no
// demo mode. `tests/journey/run.py` brings up `compose.smoke.yaml`'s
// disposable stack with the deterministic journey worker and starts the test
// edge (`tests/journey/edge.py`) on this config's `baseURL` before this file
// ever runs, and tears both down afterwards; this file only ever talks to
// that edge, the way a browser in production only ever talks to the
// operator's edge.
//

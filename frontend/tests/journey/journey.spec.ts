interface PackFile {
  name: string;
  mimeType: string;
  buffer: Buffer;
}

/** The exact bytes `journey.worker.completions_for` will hash and expect
    among the run's pinned live sources -- generated by calling the same
    `journey.pack.journey_pack()` the worker calls, never re-implemented here
    byte for byte, so admission and the worker's citation always agree. */
async function journeyPack(): Promise<PackFile[]> {
  const { stdout } = await execFileAsync(
    PYTHON,
    [
      "-c",
      "import base64, json\n" +
        "from journey.pack import journey_pack\n" +
        "print(json.dumps([[n, base64.b64encode(b).decode()] for n, b in journey_pack()]))\n",
    ],
    {
      cwd: REPO_ROOT,
      env: {
        ...process.env,
        PYTHONPATH: `${path.join(REPO_ROOT, "tests")}${path.delimiter}${REPO_ROOT}`,
      },
    },
  );
  const rows: [string, string][] = JSON.parse(stdout);
  return rows.map(([name, b64]) => ({
    name,
    mimeType: name.endsWith(".pdf") ? "application/pdf" : "text/plain",
    buffer: Buffer.from(b64, "base64"),
  }));
}

/** Restarts one `compose.smoke.yaml` service in place, using the same
    project and compose file `tests/journey/run.py` brought the stack up
    with; the environment it needs (`CAOS_EDGE_TOKEN`, `JOURNEY_STATE_DIR`,
    …) is already this process's own, inherited from that same script. */
async function restartService(service: string): Promise<void> {
  await execFileAsync(
    "docker",
    ["compose", "-p", PROJECT, "-f", COMPOSE_FILE, "--profile", "journey", "restart", service],
    { cwd: REPO_ROOT },
  );
}

/** `JOURNEY_EXIT_AFTER_FIRST_ACCEPT` (Task 4.5 decision 12) has already made
    the worker exit(137) once, and nothing in `compose.smoke.yaml` restarts
    it on its own. */
function restartJourneyWorker(): Promise<void> {
  return restartService("journey-worker");
}


  test("journey: a cross-site form post through the edge changes nothing", async ({ browser }) => {
    const sentinel = `csrf-sentinel-${randomUUID()}`;
    const body = JSON.stringify({ title: sentinel });
    const foreign = await serveCrossSitePost(`${EDGE_ORIGIN}/api/v1/cases`, body);
    // `page`'s own context came from `browser.newPage()` in `beforeAll`,
    // which Playwright limits to that one page -- a second tab needs its
    // own context, the same way the intruder persona above does. It carries
    // no cookie, so the "no session" 401 the edge answers with is exactly
    // the point: this attacker page never had the analyst's session either.
    const attackerContext = await browser.newContext();
    try {
      const attacker = await attackerContext.newPage();
      await attacker.goto(foreign.url);
      await expect.poll(() => attacker.title()).toBe("sent");
      await attacker.close();
    } finally {
      await attackerContext.close();
      await foreign.close();
    }
    await page.goto("/directory/");
    await expect(page.locator("table.reg")).not.toContainText(sentinel);
  });

  test("the served policy refuses an injected inline script and the journey records no violation", async () => {
    await page.goto(`/analysis/?case=${caseId}&run=${runId}`);
    await page.evaluate(() => {
      (window as unknown as { __cspViolations: number }).__cspViolations = 0;
      window.addEventListener("securitypolicyviolation", () => {
        (window as unknown as { __cspViolations: number }).__cspViolations += 1;
      });
    });
    await page.evaluate(() => {
      // The served policy's `require-trusted-types-for 'script'; trusted-types
      // 'none'` (decision 5) refuses even the *assignment* here -- Trusted
      // Types guards `HTMLScriptElement.textContent` as a sink, and with no
      // policy named nothing can produce the `TrustedScript` it now demands,
      // so this throws before the element is ever appended. That is a
      // stronger refusal than a script-src violation on an appended element
      // would be, and the point this test proves either way: catch it so the
      // throw itself doesn't fail the read, and let the assertions below
      // confirm the script never ran and the browser still recorded a
      // violation.
      try {
        const script = document.createElement("script");
        script.textContent = "window.__journeyInlineScriptRan = true;";
        document.body.appendChild(script);
      } catch {
        // Refused at assignment, before script-src is ever asked.
      }
    });
    const ran = await page.evaluate(
      () => (window as unknown as { __journeyInlineScriptRan?: boolean }).__journeyInlineScriptRan,
    );
    expect(ran).toBeUndefined();
    const violations = await page.evaluate(
      () => (window as unknown as { __cspViolations: number }).__cspViolations,
    );
    expect(violations).toBeGreaterThan(0);
    // The refused script left no visible trace on the workspace itself: CSP
    // is the browser's own enforcement, and nothing here logs or renders it.
    await expect(page.locator("[data-command-error], [role='alert']")).toHaveCount(0);
  });

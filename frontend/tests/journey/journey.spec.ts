function nodeLocator(page: Page, moduleId: string) {
  return page.locator(`button.node[data-node='${moduleId}']`);
}

/** Polls for a node's state over the run API directly, not by trusting the
    open SSE tail to repaint the DOM and not by reloading the page every
    cycle: the real stream stays connected (confirmed against the network
    trace) while the run genuinely progresses server-side, but a live-push
    repaint is not something this journey depends on to prove the run
    finished. An earlier version reloaded the whole page every 2s, which
    opens a fresh `/events` SSE connection per reload -- the API's SSE tail
    holds a connection until `TAIL_DEADLINE` (300s) even after the client has
    navigated away, with nothing checking for an earlier disconnect, so over
    a 320s wait that piled up abandoned connections past the API's own
    `--limit-concurrency 32` (Dockerfile) and answered later requests, in this
    test and the next one, with a bare 503. Polling the JSON directly opens
    and closes one short-lived request per cycle instead, then reloads once
    at the end to sync the DOM for the assertions that follow. */
async function waitForNode(
  page: Page,
  caseId: string,
  runId: string,
  moduleId: string,
  state: string,
  timeoutMs: number,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  let current: string | undefined;
  for (;;) {
    try {
      const response = await page.request.get(`/api/v1/cases/${caseId}/run?run=${runId}`, {
        timeout: 10_000,
      });
      if (response.ok()) {
        const body = (await response.json()) as {
          body: { run: { nodes: { module_id: string; state: string }[] } | null };
        };
        current = body.body.run?.nodes.find((n) => n.module_id === moduleId)?.state;
        if (current === state) break;
      }
    } catch {
      // A slow, refused or unparsable read counts as "not yet", never as a hang.
    }
    if (Date.now() >= deadline) {
      throw new Error(
        `${moduleId} did not reach ${state} within ${timeoutMs}ms (last: ${current})`,
      );
    }
    await page.waitForTimeout(2_000);
  }
  // Sync the visible DOM once the API confirms the state, retrying the
  // reload itself since a request right after a long wait can still meet a
  // transient 503 while other abandoned connections from this same wait
  // drain.
  await expect(async () => {
    await page.reload({ timeout: 10_000 });
    await expect(nodeLocator(page, moduleId)).toHaveAttribute("data-state", state, {
      timeout: 10_000,
    });
  }).toPass({ timeout: 30_000 });
}

/** A tiny HTTP server on its own ephemeral port -- a different origin from
    the edge on any browser's same-site rules -- serving one page that fires
    a cross-site, no-preflight ("simple request") POST at `target` the moment
    it loads. `text/plain` is CORS-safelisted, so the browser sends it with
    no permission check; whether it *changes* anything is exactly what
    decision 5's Origin / `Sec-Fetch-Site` check and `SameSite=Lax` on the
    edge's cookie are there to refuse. */
async function serveCrossSitePost(
  targetUrl: string,
  body: string,
): Promise<{ url: string; close: () => Promise<void> }> {
  const html =
    "<!doctype html><body><script>" +
    `fetch(${JSON.stringify(targetUrl)}, { method: "POST", mode: "no-cors", credentials: "include",` +
    ` headers: { "Content-Type": "text/plain" }, body: ${JSON.stringify(body)} })` +
    ".finally(() => { document.title = 'sent'; });" +
    "</script></body>";
  const server = http.createServer((_req, res) => {
    res.writeHead(200, { "content-type": "text/html" });
    res.end(html);
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const address = server.address();
  if (address === null || typeof address === "string") throw new Error("no ephemeral port");
  return {
    url: `http://127.0.0.1:${address.port}/`,
    close: () => new Promise<void>((resolve) => server.close(() => resolve())),
  };
}

